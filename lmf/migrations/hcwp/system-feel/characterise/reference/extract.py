#!/usr/bin/env python3
"""Read-only reproducible extraction check; --capture creates new files exclusively.
No fixtures, expectations, or migrated application are read by this extractor.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[5]
SLICE = HERE.parent

def sha(data):
    return hashlib.sha256(data).hexdigest()

def outputs():
    registry = json.loads((SLICE / 'source-citations.json').read_text())
    registry = registry if isinstance(registry, list) else registry['citations']
    records = {x['id']: x for x in registry}
    manifest = {}
    for line in (SLICE / 'input-files.sha256').read_text().splitlines():
        digest, path = line.split('  ', 1)
        manifest[path] = digest
    artifacts = {}
    spans = {}
    bindings = []
    for id_ in ['C001','C003','C005','C008','C010','C012','C013','C014','C015','C017','C018','C019','C020','C021','C022','C024','C027','C029','C030','C079']:
        r = records[id_]
        raw = (ROOT / r['path']).read_bytes()
        if sha(raw) != r['sha256'] or manifest[r['path']] != r['sha256']:
            raise ValueError('Input drift: ' + r['path'])
        text = '\n'.join(raw.decode('utf-8-sig').splitlines()[r['start_line']-1:r['end_line']]) + '\n'
        if r['symbol'] not in text or r['fragment'] not in text:
            raise ValueError('Unresolved extraction ' + id_)
        spans[id_] = text
        artifacts['original/' + id_ + '.txt'] = text
        bindings.append({**r, 'extractedSha256': sha(text.encode())})

    def method(text, signature):
        start = text.index(signature)
        brace = text.index('{', start)
        depth, end = 1, brace + 1
        while depth:
            depth += (text[end] == '{') - (text[end] == '}')
            end += 1
        return text[start:end]

    name = method(spans['C005'], 'protected override string ResolveCore').replace('protected override string ResolveCore(INameModel source)', 'public static string Name(ChildGeneral source)')
    address = method(spans['C008'], 'protected override string ResolveCore').replace('protected override string ResolveCore(AddressModel source)', 'public static string Address(ChildGeneral source)')
    age = method(spans['C012'], 'private static string GetAge').replace('private static', 'public static').replace('DateTime.Now', 'ReferenceClock.Now')
    org = method(spans['C017'], 'private static string GetOrganisationValue').replace('private static', 'public static').replace('(byte)LookupsUtility.CENTRE_TYPES.HEALTH_AUTHORITY', 'LookupsUtility.CENTRE_TYPES.HEALTH_AUTHORITY')
    school = method(spans['C015'], 'protected override string ResolveCore').replace('protected override string ResolveCore', 'public static object School')
    school += '\n' + method(spans['C015'], 'private static string GetChildCentreText').replace('private static string', 'private static object').replace('string.Format(CodeDescriptionFormat,', 'Resource.Format("CodeDescriptionFormat",')
    alert = spans['C018'][spans['C018'].index('public bool ShowAlert'):].strip()
    # Keep the complete delegate method; scaffold service/list/delegate construction only.
    order = method(spans['C022'], 'public void GetKdpResults')
    # Execute the original service predicate and date expression against a graph double.
    query = re.search(r'\.Where\(c => c.ClientId == clientId.*?\.ToList\(\);', spans['C021'], re.S).group()
    choices = method(spans['C027'], 'public static Dictionary')
    span = spans['C010'][spans['C010'].index('            if (value != null'):spans['C010'].rindex('            return MvcHtmlString')]
    span = span.replace('span.SetInnerText(', 'text = ').replace(');', ';')
    artifacts['Legacy.cs'] = '''// Generated by extract.py from bound original bundles. Do not hand edit.
using System;
using System.Linq;
using System.Collections.Generic;
public static class Legacy {
''' + '\n'.join([name, address, age, org, school, choices]) + '\npublic static string SpanText(object value, string format, bool leaveBlankIfNull) { string text;\n' + span + '\nreturn text; }\n}\n' + '''public class AlertModel {
public string CurrentStatusCode {get;set;}
public List<string> ChildAlerts {get;set;} = new();
''' + alert + '\n}\n' + '''public class LegacyDelegate {
public ResultService service;
public ResultTO ato;
public List<Row> listOfKdpExaminationResultDelegates;
private Row GetNewKdpExaminationResultDelegate(Row row) => row;
''' + order + '\n}\n' + '''public class ResultService {
public List<ChildExamination> entities;
public ResultTO GetKdpExamination(long clientId) {
var childExamination = entities
''' + query + '''
return new ResultTO { HcpExaminationResultToList = childExamination.Select(c => c.Saved).ToList() };
}
}
'''
    artifacts['extraction-manifest.json'] = json.dumps({'schemaVersion':1, 'bindings':bindings, 'generatedSha256':sha(artifacts['Legacy.cs'].encode()), 'adaptations':'README.md#extraction-and-adaptations'}, indent=2) + '\n'
    return artifacts

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--capture', action='store_true')
    args = parser.parse_args()
    files = outputs()
    if args.capture:
        if any((HERE / p).exists() for p in files):
            raise SystemExit('Extraction destination exists; refusing overwrite')
        for path, text in files.items():
            dest = HERE / path
            dest.parent.mkdir(parents=True, exist_ok=True)
            with dest.open('x') as f:
                f.write(text)
    else:
        for path, text in files.items():
            if (HERE / path).read_bytes() != text.encode():
                raise SystemExit('Extraction mismatch: ' + path)
    print(json.dumps({'extractedArtifacts':len(files), 'mode':'capture' if args.capture else 'read-only-compare', 'passed':True}))

if __name__ == '__main__':
    main()
